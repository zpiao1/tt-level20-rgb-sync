"""LED index groups for the Thermaltake Level 20 RGB.

Index groups are documented by the community SignalRGB plugin, which recovered
them from iTAKE USB captures. Key LEDs occupy indexes below 0x82; everything
from 0x82 up is decorative lighting (centre strip + the outer "U-frame").
"""

# 11 reports x 15 LED indexes, exactly as the hardware groups them for transfer.
REPORT_INDEXES = [
    [0x60,0x61,0x62,0x63,0x68,0x69,0x6A,0x40,0x41,0x42,0x7B,0x7C,0x7D,0x00,0x01],
    [0x08,0x09,0x10,0x11,0x18,0x19,0x20,0x21,0x28,0x29,0x30,0x31,0x02,0x03,0x0A],
    [0x0B,0x12,0x13,0x1A,0x1B,0x22,0x23,0x2A,0x2B,0x32,0x33,0x04,0x05,0x0C,0x0D],
    [0x14,0x15,0x1C,0x1D,0x24,0x25,0x2C,0x2D,0x34,0x06,0x07,0x0E,0x0F,0x16,0x17],
    [0x1E,0x1F,0x26,0x27,0x2E,0x2F,0x5B,0x5A,0x5C,0x5D,0x5E,0x5F,0x3C,0x36,0x66],
    [0x67,0x6B,0x38,0x39,0x78,0x3A,0x3B,0x7A,0x3D,0x3F,0x3E,0x7E,0x48,0x49,0x50],
    [0x51,0x4A,0x4B,0x52,0x53,0x4C,0x4D,0x54,0x4E,0x4F,0x56,0x55,0x7F,0x57,0xB1],
    [0xB2,0x44,0x75,0x45,0x76,0x46,0x86,0x87,0x85,0x84,0x83,0x82,0x8F,0x8E,0x8D],
    [0x8C,0x8B,0xA3,0xA2,0xA1,0xA0,0xAF,0xAE,0xAD,0xAC,0xAB,0xAA,0xA9,0xA8,0xB7],
    [0xB6,0xB5,0xB4,0xB3,0x8A,0x89,0x88,0x97,0x96,0x95,0x94,0x93,0x92,0x91,0x90],
    [0x9F,0x9A,0x99,0x98,0xA7,0xA6,0x88,0x97,0x96,0x95,0x94,0x93,0x92,0x91,0x90],
]

ALL_INDEXES = sorted({i for report in REPORT_INDEXES for i in report})

# Everything at/above this index is decorative rather than a key.
DECOR_FLOOR = 0x82

KEYS         = [i for i in ALL_INDEXES if i < DECOR_FLOOR]
DECORATIVE   = [i for i in ALL_INDEXES if i >= DECOR_FLOOR]

CENTER_STRIP = [0x86, 0x87, 0x85, 0x84, 0x83, 0x82, 0x8F, 0x8E, 0x8D, 0x8C, 0x8B]
OUTER_LEFT   = [0xA3, 0xA2, 0xA1, 0xA0, 0xAF, 0xAE, 0xAD]

# Branding LEDs. These sit in the decorative index range but are not part of the
# light frame, and pulsing them looks wrong - the logo should stay steady.
LEFT_TT_LOGO   = 0xB1
AUXILIARY_LOGO = 0xB2
LOGOS = [LEFT_TT_LOGO, AUXILIARY_LOGO]

# The rest of the U-frame (bottom edge + right vertical). The plugin documents
# the frame's extent but not an unambiguous ordering, so derive by subtraction
# rather than hardcoding a guessed sequence.
OUTER_REST   = [i for i in DECORATIVE
                if i not in CENTER_STRIP and i not in OUTER_LEFT and i not in LOGOS]

# Default target for the reactive pulse: the whole outer frame, not the keys.
OUTER_FRAME  = OUTER_LEFT + OUTER_REST

GROUPS = {
    "keys":         KEYS,
    "logos":        LOGOS,
    "center":       CENTER_STRIP,
    "outer_left":   OUTER_LEFT,
    "outer_rest":   OUTER_REST,
    "outer_frame":  OUTER_FRAME,
    "decorative":   DECORATIVE,
    "all":          ALL_INDEXES,
}


def reports_touching(indexes):
    """Which report numbers must be resent to update these indexes."""
    wanted = set(indexes)
    return [n for n, report in enumerate(REPORT_INDEXES) if wanted & set(report)]


if __name__ == "__main__":
    for name, group in GROUPS.items():
        print(f"{name:<12} {len(group):>3} LEDs   reports: {reports_touching(group)}")
